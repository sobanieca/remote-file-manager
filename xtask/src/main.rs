//! Development tasks, run through the cargo aliases in `.cargo/config.toml`:
//!
//! - `cargo verify`: formatting, lints and tests (run before committing)
//! - `cargo build-ui`: builds `ui/` with imp and embeds the build into the
//!   server (`src/ui-assets/` and the generated `src/ui_assets.rs`)
//! - `cargo xtask bundle-ui`: embeds an existing `ui/dist` without building
//! - `cargo dev`: builds the UI and serves `test/`

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("workspace root")
        .to_path_buf()
}

fn cargo(args: &[&str], cwd: &Path) -> bool {
    println!("> cargo {}", args.join(" "));
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    Command::new(cargo)
        .args(args)
        .current_dir(cwd)
        .status()
        .is_ok_and(|status| status.success())
}

fn imp_build() -> bool {
    println!("> imp build --env prod");
    match Command::new("imp")
        .args(["build", "--env", "prod"])
        .current_dir(root().join("ui"))
        .status()
    {
        Ok(status) => status.success(),
        Err(err) => {
            eprintln!("Failed to run imp: {err}");
            false
        }
    }
}

fn collect_files(dir: &Path, base: &Path, files: &mut Vec<String>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            collect_files(&path, base, files)?;
        } else {
            let relative = path.strip_prefix(base).expect("file below base");
            files.push(relative.to_string_lossy().replace('\\', "/"));
        }
    }
    Ok(())
}

fn bundle_ui() -> Result<usize, String> {
    let root = root();
    let dist = root.join("ui/dist");
    let assets_dir = root.join("src/ui-assets");
    let mut files = Vec::new();
    collect_files(&dist, &dist, &mut files)
        .map_err(|err| format!("Failed to read {}: {err}", dist.display()))?;
    if !files.iter().any(|file| file == "index.html") {
        return Err(format!(
            "No index.html in {} - run imp build first",
            dist.display()
        ));
    }
    files.sort();

    if assets_dir.exists() {
        std::fs::remove_dir_all(&assets_dir)
            .map_err(|err| format!("Failed to clear {}: {err}", assets_dir.display()))?;
    }
    for file in &files {
        let target = assets_dir.join(file);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|err| format!("Failed to create {}: {err}", parent.display()))?;
        }
        std::fs::copy(dist.join(file), &target)
            .map_err(|err| format!("Failed to copy {file}: {err}"))?;
    }

    let mut source = String::from(
        "//! Generated by `cargo build-ui` from the imp build in ui/dist - do not edit.\n\n\
         #[rustfmt::skip]\n\
         pub const UI_ASSETS: &[(&str, &[u8])] = &[\n",
    );
    for file in &files {
        source.push_str(&format!(
            "    ({file:?}, include_bytes!(\"ui-assets/{file}\")),\n"
        ));
    }
    source.push_str("];\n");
    let output = root.join("src/ui_assets.rs");
    std::fs::write(&output, source)
        .map_err(|err| format!("Failed to write {}: {err}", output.display()))?;
    Ok(files.len())
}

fn embed_ui() -> bool {
    match bundle_ui() {
        Ok(count) => {
            println!("Bundled {count} UI assets into src/ui-assets");
            true
        }
        Err(message) => {
            eprintln!("{message}");
            false
        }
    }
}

fn main() -> ExitCode {
    let task = std::env::args().nth(1).unwrap_or_default();
    let root = root();
    let ok = match task.as_str() {
        "verify" => {
            cargo(&["fmt", "--all", "--check"], &root)
                && cargo(
                    &[
                        "clippy",
                        "--workspace",
                        "--all-targets",
                        "--",
                        "-D",
                        "warnings",
                    ],
                    &root,
                )
                && cargo(&["test", "--workspace"], &root)
        }
        "build-ui" => imp_build() && embed_ui(),
        "bundle-ui" => embed_ui(),
        "dev" => {
            imp_build()
                && embed_ui()
                && cargo(&["run", "--quiet", "--package", "rfm"], &root.join("test"))
        }
        _ => {
            eprintln!("Usage: cargo xtask <verify|build-ui|bundle-ui|dev>");
            false
        }
    };
    if ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}
